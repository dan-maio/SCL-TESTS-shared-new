#!/usr/bin/env python3
"""gen-imports.py — auto-generate the import surface for an optimal-shared app.

Reads every shared library (`.so`) produced by the fixture build and emits, with
NO hand editing:

  1. imports.generated.h  — one `extern "C"` declaration per exported symbol, so
     `main` can name each function/global directly. Functions are declared as
     `void name(void)` placeholders; you call them by NAME with a cast to the real
     prototype, e.g.  ((unsigned(*)(unsigned,unsigned))s_add)(10, 5).
     That is the whole calling contract: the name of the function (+ a cast).

  2. modules.generated.inc — the ordered list of `.so` basenames, so the loader in
     `main` is a plain loop (provision -> load -> patch_main) with no hard-coded
     names. Adding a library = dropping a `.so` in the fixtures dir and rebuilding;
     `main.cpp` is never touched.

Why a cast and not the real prototype? Argument/return types are not recorded in
an ELF symbol table — only the library's own API header carries them. So we give
you the *name* (a real, linkable symbol whose GOT slot patch_main() fills at load)
and you supply the type at the call site. If a library ships a normal API header,
just include that instead; this file is the zero-header fallback.

Usage:  gen-imports.py <out_header> <out_modules_inc> <readelf> <lib1.so> [lib2.so ...]
"""
import subprocess
import sys
import os


def exported_symbols(readelf, so):
    """Return [(name, kind)] for GLOBAL/WEAK, defined (Ndx != UND) FUNC/OBJECT."""
    out = subprocess.check_output([readelf, "-W", "--dyn-syms", so],
                                  text=True, stderr=subprocess.DEVNULL)
    syms = []
    for line in out.splitlines():
        f = line.split()
        # Num: Value Size Type Bind Vis Ndx Name
        if len(f) < 8 or not f[0].endswith(":"):
            continue
        typ, bind, ndx, name = f[3], f[4], f[6], f[7]
        if bind not in ("GLOBAL", "WEAK"):
            continue
        if ndx == "UND":
            continue
        if typ not in ("FUNC", "OBJECT"):
            continue
        name = name.split("@")[0]           # strip version suffix if any
        if not name or not name[0].isalpha() and name[0] != "_":
            continue
        syms.append((name, typ))
    return syms


def main(argv):
    if len(argv) < 5:
        sys.stderr.write(__doc__)
        return 2
    out_h, out_inc, readelf = argv[1], argv[2], argv[3]
    libs = argv[4:]

    seen = {}          # name -> kind (first definition wins; dup across libs OK)
    order = []
    modules = []
    for so in libs:
        modules.append(os.path.basename(so))
        for name, kind in exported_symbols(readelf, so):
            if name in seen:
                continue
            seen[name] = kind
            order.append(name)

    with open(out_h, "w") as h:
        h.write("// AUTO-GENERATED by tools/gen-imports.py — DO NOT EDIT.\n")
        h.write("// One declaration per exported library symbol. Call functions by\n")
        h.write("// NAME with a cast to the real prototype; read globals by NAME.\n")
        h.write("#pragma once\n\n")
        h.write('extern "C" {\n')
        for name in order:
            if seen[name] == "FUNC":
                h.write(f"void {name}(void);            // function: cast at the call site\n")
            else:
                h.write(f"extern unsigned char {name};   // global: take &{name}, cast as needed\n")
        h.write("}\n")

    with open(out_inc, "w") as inc:
        inc.write("// AUTO-GENERATED by tools/gen-imports.py — DO NOT EDIT.\n")
        inc.write("// Ordered list of module basenames for the loader loop in main.\n")
        for m in modules:
            inc.write(f'"{m}",\n')

    sys.stderr.write(f"gen-imports: {len(order)} symbols from {len(modules)} modules\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
