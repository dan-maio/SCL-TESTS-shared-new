#!/usr/bin/env bash
# Build fixtures/floatlib.so with the SCL no-pic recipe AND derive the SRAM window
# from RAM geometry (no typed addresses) -> emits fixtures/windows.generated.ld,
# which src/app-windows.ld INCLUDEs. Single library => the window is exactly its size.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$HERE/.."; SCL="$(cd "$HERE/../platform" && pwd)"; OUT="$HERE"   # SCL from git
SCLSHARED="$(cd "$HERE/../SCL-shared" && pwd)"
APP_LD="$ROOT/src/app-windows.ld"
LD_TMPL="$SCL/fixtures-src/ldscripts/nopic-split.ld"
TC="${ARM_TOOLCHAIN_BIN:-/home/dan/.local/xPacks/@xpack-dev-tools/arm-none-eabi-gcc/15.2.1-1.1.1/.content/bin}"
CXX="$TC/arm-none-eabi-g++"; READELF="$TC/arm-none-eabi-readelf"

MCU="-mcpu=cortex-m4 -mthumb -mfloat-abi=hard -mfpu=fpv4-sp-d16"
NOPIC="-fno-pic -mlong-calls"; OPT="-O0 -ffunction-sections -fdata-sections"
CXXFLAGS="-std=c++20 -nostdlib -nodefaultlibs -fno-exceptions -fno-rtti -fno-threadsafe-statics -fno-use-cxa-atexit"
LDFLAGS="-Wl,-E -Wl,-z,max-page-size=0x100 -Wl,--unresolved-symbols=ignore-all -Wl,--gc-sections"

# ---- RAM geometry from the app script (device geometry, not window addresses) ----
tonum() { local v="${1//K/*1024}"; v="${v//M/*1024*1024}"; echo $(( v )); }
RAM_LINE=$(grep -E 'RAM[[:space:]]*\(rwx\)[[:space:]]*:' "$APP_LD" | head -1)
RAM_ORIGIN=$(tonum "$(sed -nE 's/.*ORIGIN[[:space:]]*=[[:space:]]*(0x[0-9A-Fa-f]+).*/\1/p' <<<"$RAM_LINE")")
RAM_LEN=$(tonum "$(sed -nE 's/.*LENGTH[[:space:]]*=[[:space:]]*([0-9]+[KM]?).*/\1/p' <<<"$RAM_LINE")")
STACK=$(tonum "$(sed -nE 's/.*__Main_Stack_Size[[:space:]]*=[[:space:]]*([0-9]+([[:space:]]*\*[[:space:]]*[0-9]+)*).*/\1/p' "$APP_LD" | head -1 | tr -d ' ')")
RAM_TOP=$(( RAM_ORIGIN + RAM_LEN ))
align_up(){ echo $(( ($1+$2-1) & ~($2-1) )); }; align_down(){ echo $(( $1 & ~($2-1) )); }

build_at() { # textbase database
  sed -e "s/__TEXT_BASE__/$1/g" -e "s/__DATA_BASE__/$2/g" "$LD_TMPL" > "$OUT/floatlib.ld"
  "$CXX" $MCU $NOPIC $OPT $CXXFLAGS -shared -nostartfiles $LDFLAGS -T "$OUT/floatlib.ld" \
      -I "$HERE/include" -o "$OUT/floatlib.so" "$HERE/src/floatlib.cpp"
}
# pass 1: build at a placeholder, measure
build_at $(printf '0x%x' $((RAM_ORIGIN+RAM_LEN/4))) $(printf '0x%x' $((RAM_ORIGIN+RAM_LEN/2)))
TXT=$("$READELF" -l "$OUT/floatlib.so" | awk '$1=="LOAD" && $7=="R"{print $6;exit}')
DAT=$("$READELF" -l "$OUT/floatlib.so" | awk '$1=="LOAD" && $7~/W/{print $6;exit}')
FILE=$(stat -c%s "$OUT/floatlib.so")
# derive window top-down below the stack
DATA_END=$(align_down $(( RAM_TOP - STACK )) 8)
DATA_START=$(align_down $(( DATA_END - $(align_up $DAT 0x100) )) 8)
TEXT_END=$DATA_START
TEXT_START=$(align_down $(( TEXT_END - $(align_up $TXT 0x100) )) 0x20)
ARENA=$(align_up "$FILE" 0x400)
# pass 2: relink at the derived base
build_at $(printf '0x%x' $TEXT_START) $(printf '0x%x' $DATA_START)

cat > "$OUT/windows.generated.ld" <<LD
/* AUTO-GENERATED by fixtures/build.sh — DO NOT EDIT (derived from RAM geometry). */
_simage_arena_size = $(printf '0x%x' $ARENA) ;
_sxip_text_start   = $(printf '0x%x' $TEXT_START) ;
_sxip_text_end     = $(printf '0x%x' $TEXT_END) ;
_sxip_data_start   = $(printf '0x%x' $DATA_START) ;
_sxip_data_end     = $(printf '0x%x' $DATA_END) ;
LD
echo "floatlib.so" > "$OUT/manifest.txt"; echo "floatlib.so" > "$OUT/link.txt"
printf 'floatlib.so  text 0x%x  data 0x%x  window text 0x%x..0x%x  arena 0x%x\n' \
    "$TEXT_START" "$DATA_START" "$TEXT_START" "$TEXT_END" "$ARENA"
